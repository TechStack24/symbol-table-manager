#!/usr/bin/env python3
"""Regenerate standalone/symbol_table_manager.py from the modules in compiler/.

The single-file version is the concatenation of the compiler modules (relative
imports and module docstrings removed) followed by the command-line interface
that already lives in the standalone file. Run this after changing compiler/*.py:

    python tools/build_standalone.py
"""

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "standalone" / "symbol_table_manager.py"
MODULES = ["tokens", "typeinfo", "symbol_table", "lexer", "parser", "analyzer", "playground"]
CLI_MARKER = "# PART: command-line interface (user input)"

HEADER = '''#!/usr/bin/env python3
"""
Symbol Table Manager - single-file version with user input.

A C-subset compiler front end (preprocessor + lexer + parser + scoped hash-based
symbol table). Everything lives in this one file and needs only the Python
standard library. (Generated by tools/build_standalone.py - edit compiler/*.py instead.)

Run:
    python symbol_table_manager.py              # interactive menu
    python symbol_table_manager.py prog.c       # analyze a file directly
    python symbol_table_manager.py < prog.c     # analyze piped input

In the menu you can:
    1) type or paste your own C program (finish with a line containing only END)
    2) load a program from a file
    3) use the playground (insert / lookup / delete / enter / exit commands)
    4) run a built-in sample
"""

import re
import sys
from collections import Counter, namedtuple
from dataclasses import asdict, dataclass, field, replace
from typing import Optional

'''


def strip_module(text):
    """Drop the docstring and all top-level imports, keep everything else."""
    tree = ast.parse(text)
    lines = text.splitlines()
    for node in tree.body:
        is_doc = (isinstance(node, ast.Expr) and isinstance(node.value, ast.Constant)
                  and isinstance(node.value.value, str))
        if isinstance(node, (ast.Import, ast.ImportFrom)) or (is_doc and node is tree.body[0]):
            for n in range(node.lineno - 1, node.end_lineno):
                lines[n] = ""
    return "\n".join(lines).strip("\n") + "\n"


def main():
    old = TARGET.read_text(encoding="utf-8")
    cli = old[old.index("# ====", old.index(CLI_MARKER) - 80):]
    cli = cli.replace("mini-C", "C")
    parts = []
    for name in MODULES:
        body = strip_module((ROOT / "compiler" / f"{name}.py").read_text(encoding="utf-8"))
        title = name.replace("_", " ")
        parts.append(f"# {'=' * 70}\n# PART: {title}\n# {'=' * 70}\n\n{body}")
    TARGET.write_text(HEADER + "\n".join(parts) + "\n" + cli, encoding="utf-8")
    compile(TARGET.read_text(encoding="utf-8"), str(TARGET), "exec")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(TARGET.read_text().splitlines())} lines)")


if __name__ == "__main__":
    sys.exit(main())
